const QUOTE_GROUP={lian:'_F',jia:'_F',lian2:'_F',te:'_F',cmdr:'_F',ying:'_N',xu:'_N',ye:'_N',wuking:'_N',yuanwu:'_N'};
function quoteKey(u){
  if(!u) return null;
  if(u.cid&&QUOTES[u.cid]) return u.cid;
  if(u.tag&&QUOTES[u.tag]) return u.tag;
  if(u.merc) return null;
  if(u.side==='E') return QUOTE_GROUP[u.cls]||'_E';
  return null;
}
function pickQuote(u,kind,opp){
  const k=quoteKey(u); if(!k) return '';
  const q=QUOTES[k], ok=quoteKey(opp);
  if((kind==='atk'||kind==='sp')&&q.vs&&ok&&q.vs[ok]) return q.vs[ok][Math.floor(Math.random()*q.vs[ok].length)];
  const list=q[kind]||(kind==='sp'?q.atk:null); if(!list||!list.length) return '';
  return list[Math.floor(Math.random()*list.length)];
}
