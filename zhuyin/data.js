  function parseSyl(z) {
    let tone = 0;
    let s = z;
    if (s.endsWith('ˊ')) tone = 1; else if (s.endsWith('ˇ')) tone = 2;
    else if (s.endsWith('ˋ')) tone = 3; else if (s.endsWith('˙')) tone = 4;
    if (tone) s = s.slice(0, -1);
    return { parts: Array.from(s), tone };
  }
